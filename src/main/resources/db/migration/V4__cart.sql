-- Cart of the shop window (giro 008). Additions only. ADR-0003 point 8 (SchemaRulesTest):
-- tenant_id with a foreign key to tenant(id), unique (tenant_id, id), an index starting
-- with tenant_id. Foreign keys are composite with tenant_id: a row cannot point to a row
-- of another shop.

create table cart (
  id         bigint generated always as identity primary key,
  tenant_id  text not null references tenant(id),
  token      text not null,                 -- random, generated by the server
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version    bigint not null default 0,
  constraint cart_tenant_id_id_key unique (tenant_id, id),
  constraint cart_token_key unique (token)
);

create table cart_item (
  id         bigint generated always as identity primary key,
  tenant_id  text not null references tenant(id),
  cart_id    bigint not null,
  variant_id bigint not null,
  quantity   int not null check (quantity between 1 and 20),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version    bigint not null default 0,
  constraint cart_item_tenant_id_id_key unique (tenant_id, id),
  constraint cart_item_cart_id_variant_id_key unique (cart_id, variant_id),
  constraint cart_item_cart_fkey
    foreign key (tenant_id, cart_id) references cart (tenant_id, id) on delete cascade,
  constraint cart_item_variant_fkey
    foreign key (tenant_id, variant_id) references product_variant (tenant_id, id)
);

create index cart_item_tenant_id_cart_id_idx on cart_item (tenant_id, cart_id);
